-- IT Friend Finder PostgreSQL schema.
-- Create it_friend_finder separately, connect to it, then run this file.

CREATE TYPE user_role AS ENUM ('MEMBER','COMMUNITY_LEADER','ADMIN');
CREATE TYPE experience_level AS ENUM ('Beginner','Intermediate','Advanced');
CREATE TYPE collaboration_type AS ENUM ('Mostly Discussion','Mostly Projects','Both');
CREATE TYPE activity_level AS ENUM ('Casual','Few Times Per Week','Daily');
CREATE TYPE user_goal AS ENUM ('Friends','Study Partners','Project Partners','Mentorship','Professional Networking');
CREATE TYPE friend_request_status AS ENUM ('PENDING','ACCEPTED','REJECTED');
CREATE TYPE post_status AS ENUM ('PENDING','APPROVED','REJECTED');
CREATE TYPE conversation_type AS ENUM ('PRIVATE','GROUP');

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(100) NOT NULL, username VARCHAR(30) NOT NULL UNIQUE,
    email VARCHAR(160) NOT NULL UNIQUE, password_hash VARCHAR(200) NOT NULL,
    role user_role NOT NULL DEFAULT 'MEMBER', bio VARCHAR(500) NOT NULL DEFAULT '',
    suspended BOOLEAN NOT NULL DEFAULT FALSE, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE interests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(100) NOT NULL UNIQUE
);
CREATE TABLE questionnaire_responses (
    user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    experience experience_level NOT NULL, collaboration collaboration_type NOT NULL,
    activity activity_level NOT NULL, updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE OR REPLACE FUNCTION update_questionnaire_timestamp() RETURNS TRIGGER AS $$
BEGIN NEW.updated_at = CURRENT_TIMESTAMP; RETURN NEW; END; $$ LANGUAGE plpgsql;
CREATE TRIGGER trg_questionnaire_updated_at BEFORE UPDATE ON questionnaire_responses
FOR EACH ROW EXECUTE FUNCTION update_questionnaire_timestamp();
CREATE TABLE user_interests (
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    interest_id BIGINT NOT NULL REFERENCES interests(id), rating SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
    PRIMARY KEY (user_id, interest_id)
);
CREATE TABLE user_goals (
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    goal user_goal NOT NULL, PRIMARY KEY (user_id, goal)
);
CREATE TABLE communities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    interest_id BIGINT REFERENCES interests(id), name VARCHAR(100) NOT NULL UNIQUE,
    description VARCHAR(1000) NOT NULL, leader_id BIGINT REFERENCES users(id),
    active BOOLEAN NOT NULL DEFAULT TRUE, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE community_members (
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    community_id BIGINT NOT NULL REFERENCES communities(id),
    joined_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, PRIMARY KEY (user_id, community_id)
);
CREATE TABLE friend_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_id BIGINT NOT NULL REFERENCES users(id), receiver_id BIGINT NOT NULL REFERENCES users(id),
    status friend_request_status NOT NULL DEFAULT 'PENDING',
    pair_low BIGINT GENERATED ALWAYS AS (LEAST(sender_id, receiver_id)) STORED,
    pair_high BIGINT GENERATED ALWAYS AS (GREATEST(sender_id, receiver_id)) STORED,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, responded_at TIMESTAMPTZ,
    UNIQUE (pair_low, pair_high), CHECK (sender_id <> receiver_id)
);
CREATE TABLE posts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    community_id BIGINT NOT NULL REFERENCES communities(id), author_id BIGINT NOT NULL REFERENCES users(id),
    title VARCHAR(160) NOT NULL, body TEXT NOT NULL, status post_status NOT NULL DEFAULT 'PENDING',
    moderated_by BIGINT REFERENCES users(id), moderated_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_posts_community_status ON posts (community_id, status);
CREATE TABLE comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id BIGINT NOT NULL REFERENCES posts(id), author_id BIGINT NOT NULL REFERENCES users(id),
    body VARCHAR(2000) NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE conversations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type conversation_type NOT NULL, name VARCHAR(100) NOT NULL DEFAULT '',
    creator_id BIGINT NOT NULL REFERENCES users(id), private_low BIGINT REFERENCES users(id),
    private_high BIGINT REFERENCES users(id), created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (private_low, private_high),
    CHECK ((type = 'PRIVATE' AND private_low IS NOT NULL AND private_high IS NOT NULL AND private_low < private_high)
        OR (type = 'GROUP' AND private_low IS NULL AND private_high IS NULL))
);
CREATE TABLE conversation_members (
    conversation_id BIGINT NOT NULL REFERENCES conversations(id), user_id BIGINT NOT NULL REFERENCES users(id),
    PRIMARY KEY (conversation_id, user_id)
);
CREATE TABLE messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL, sender_id BIGINT NOT NULL, body VARCHAR(4000) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (conversation_id, sender_id) REFERENCES conversation_members(conversation_id, user_id)
);
CREATE INDEX idx_messages_conversation_id ON messages (conversation_id, id);
CREATE TABLE activity_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id), event VARCHAR(50) NOT NULL,
    community_id BIGINT REFERENCES communities(id), created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_activity_logs_created_event ON activity_logs (created_at, event);
